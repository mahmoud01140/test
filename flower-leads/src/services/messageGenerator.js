/**
 * منشئ رسائل الواتساب التسويقية المخصصة لكل محل
 * باللغة العربية المصرية الراقية والمهنية
 */

function generateMarketingMessage(shop) {
  const shopName = shop.name || 'عالم الزهور';
  const locationText = shop.city
    ? `في ${shop.city}`
    : shop.governorate
    ? `بمحافظة ${shop.governorate}`
    : '';

  // تخصيص استهلال الرسالة
  let greeting = `السلام عليكم، أستاذ/فريق ${shopName} 🌸`;

  // تخصيص فقرة النشاط
  let businessNotice = locationText
    ? `أنا مطور مواقع إلكترونية، وكنت معجب جدًا بذوق وتنسيقات الورد الخاصة بحضراتكم ${locationText}.`
    : `أنا مطور مواقع إلكترونية، ولاحظت تميزكم في تنسيق باقات الورد وهدايا المناسبات.`;

  // سياق وجود موقع أو عدمه
  let websiteContext = '';
  if (shop.hasWebsite === false) {
    websiteContext = `حابب أعرض على حضراتكم فكرة نموذج تجريبي (Live Demo) لموقع إلكتروني ذكي وسريع مخصص لمحلات الورد، يقدر الزبون من خلاله يتصفح البوكيهات بالأسعار ويطلب مباشرة على واتساب بدون ما تضيعوا وقت في الرد اليدوي على كل استفسار.`;
  } else if (shop.hasWebsite === true) {
    websiteContext = `حابب أعرض على حضراتكم فكرة نموذج حديث لتطوير واجهة الويب وربطها بنظام طلبات واتساب تفاعلي يسهل على العملاء اختيار البوكيه والمناسبة بسرعة من الموبايل.`;
  } else {
    websiteContext = `حابب أعرض على حضراتكم نموذجًا تجريبيًا (Live Demo) لشكل موقع إلكتروني مخصص لمحلات الورد، يقدر يعرض تنسيقاتكم وصور البوكيهات ويسهّل استقبال طلبات العملاء عبر واتساب بضغطة زر واحدة.`;
  }

  const closing = `لو الفكرة مناسبة لحضرتكم، يشرفني إلقاء نظرة على النموذج ونناقش إمكانية تخصيصه وتطويره بما يخدم نشاطكم ويزود المبيعات.

تحياتي وتقديري لحضراتكم 🤝`;

  return `${greeting}

${businessNotice}

${websiteContext}

${closing}`.trim();
}

module.exports = {
  generateMarketingMessage
};

